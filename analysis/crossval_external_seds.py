def main() -> None:
    parser = argparse.ArgumentParser(
        description="Crossval visualizations: tengri vs external codes."
    )
    parser.add_argument("--save-pdf", action="store_true", help="Also save PDF alongside PNG")
    parser.add_argument("--show", action="store_true", help="Show interactive plots")
    parser.add_argument(
        "--only",
        choices=["stellar", "metallicity", "sfh", "nebular", "dust_laws", "summary"],
        default=None,
        help="Produce only one figure group",
    )
    parser.add_argument(
        "--no-tengri",
        action="store_true",
        help="Skip building tengri SEDs (show external codes only)",
    )
    args = parser.parse_args()

    import matplotlib

    if not args.show:
        matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    if not _REF_PATH.is_file():
        print(f"ERROR: Reference file not found: {_REF_PATH}")
        print("Run: python scripts/generate_external_sed_reference.py")
        sys.exit(1)

    ref = dict(np.load(str(_REF_PATH), allow_pickle=True))
    wave = ref["wave_grid"]
    n_keys = len([k for k in ref if not k.startswith("wave")])
    print(f"Loaded reference: {_REF_PATH}  ({n_keys} SED arrays)")

    # Build tengri SEDs live and inject into ref dict
    if not args.no_tengri:
        if not _SSP_PATH.is_file():
            print(f"WARNING: SSP file not found: {_SSP_PATH}")
            print("  Proceeding without tengri SEDs (pass --no-tengri to suppress this warning).")
        else:
            import jax

            jax.config.update("jax_enable_x64", True)
            from tengri.models.sps.dsps_wrapper import load_ssp_data

            ssp_data = load_ssp_data(str(_SSP_PATH))
            tengri_seds = _build_all_tengri_seds(ssp_data, wave)
            ref.update(tengri_seds)
            print(f"  Injected {len(tengri_seds)} tengri SEDs into reference dict.")

    # Print quick numerical summary before plotting
    _print_consistency_report(ref, wave)

    FIG_DIR.mkdir(parents=True, exist_ok=True)

    figures: dict = {}
    all_group_stats: dict[str, dict[str, dict[str, float]]] = {}

    def _maybe_make(group_id: str, cases, title, fs=None):
        if args.only is not None and args.only != group_id:
            return
        fig, stats = _make_group_figure(wave, ref, cases, title, figsize=fs)
        figures[group_id] = fig
        all_group_stats[group_id] = stats

    _maybe_make(
        "stellar",
        _GROUP_STELLAR,
        "Stellar & dust attenuation — tengri vs FSPS / bagpipes",
        fs=(13, 16),
    )
    _maybe_make(
        "metallicity",
        _GROUP_METALLICITY,
        "Metallicity grid — tengri vs FSPS / bagpipes",
        fs=(13, 13),
    )
    _maybe_make(
        "sfh",
        _GROUP_SFH,
        "SFH shapes (exp-τ, log-normal, DPL) — tengri vs FSPS / bagpipes",
        fs=(13, 35),
    )
    _maybe_make(
        "nebular",
        _GROUP_NEBULAR,
        "Nebular emission — FSPS vs bagpipes (BakedIn) [tengri nebular crossval pending]",
        fs=(13, 16),
    )
    _maybe_make(
        "dust_laws",
        _GROUP_DUST_LAWS,
        "Extinction laws: SMC / LMC (Gordon+2003) and CCM (Cardelli+1989) — FSPS vs bagpipes",
        fs=(13, 29),
    )

    # Summary figure
    if args.only is None or args.only == "summary":
        fig_sum = _make_summary_figure(all_group_stats)
        figures["summary"] = fig_sum

    # ── Save ──────────────────────────────────────────────────────────────
    for name, fig in figures.items():
        out_png = FIG_DIR / f"crossval_{name}.png"
        fig.savefig(out_png, bbox_inches="tight", dpi=150)
        print(f"Saved: {out_png}")
        if args.save_pdf:
            out_pdf = FIG_DIR / f"crossval_{name}.pdf"
            fig.savefig(out_pdf, bbox_inches="tight", dpi=150)
            print(f"Saved: {out_pdf}")

    if args.show:
        plt.show()

    for fig in figures.values():
        plt.close(fig)


if __name__ == "__main__":
    main()
