def _print_consistency_report(ref: dict, wave: np.ndarray) -> None:
    """Print table of median |Δ| for every tengri↔code pair."""
    print()
    print("=" * 72)
    print(f"{'Case':<38} {'tengri/FSPS':>12} {'bags/FSPS':>12} {'cig/FSPS':>10}")
    print("=" * 72)

    all_cases = [
        s
        for _, cases in [
            ("stellar", _GROUP_STELLAR),
            ("metallicity", _GROUP_METALLICITY),
            ("sfh", _GROUP_SFH),
            ("nebular", _GROUP_NEBULAR),
            ("dust_laws", _GROUP_DUST_LAWS),
        ]
        for s, _ in cases
    ]

    for suffix in all_cases:
        fsps_key = f"fsps_{suffix}"
        tengri_key = f"tengri_{suffix}"
        bags_key = f"bagpipes_{suffix}"
        cig_key = f"cigale_{suffix}"
        if fsps_key not in ref:
            continue
        fsps = ref[fsps_key]
        t_str = (
            f"{_median_abs_resid(ref[tengri_key], fsps, wave):.3f}"
            if tengri_key in ref
            else "  n/a"
        )
        b_str = (
            f"{_median_abs_resid(ref[bags_key], fsps, wave):.3f}" if bags_key in ref else "  n/a"
        )
        c_str = f"{_median_abs_resid(ref[cig_key], fsps, wave):.3f}" if cig_key in ref else "  n/a"
        # Flag large tengri deviations
        flag = ""
        if tengri_key in ref:
            v = _median_abs_resid(ref[tengri_key], fsps, wave)
            flag = " ⚠" if not np.isnan(v) and v > _TOL_SAME_SSP else ""
        print(f"{suffix:<38} {t_str:>12} {b_str:>12} {c_str:>10}{flag}")

    print("=" * 72)
    print("  ⚠ = tengri median |Δ| > 25% (same-SSP tolerance)")
    print("  n/a = tengri comparison not available for this case:")
    print("    - expsfh_*: FSPS/bagpipes use declining tau (SFR peaks at galaxy formation).")
    print("      tengri has no declining-tau SFH type; its 'exp'/'dexp' peak in the")
    print("      recent past. Comparing them would show SFH shape mismatch, not code errors.")
    print("      See docs/known_bugs.md CROSSVAL-02.")
    print("    - nebular_*: requires separate SSP with ionising-photon table.")
    print("    - smc_*/lmc_*/ccm_*: FSPS/bagpipes use a single-component screen model.")
    print("      tengri uses the same Pei (1992) / Cardelli (1989) extinction curves but")
    print("      within a two-component Charlot & Fall geometry (τ_BC/τ_diff), so a")
    print("      direct screen-model comparison would conflate code vs. geometry differences.")
    print()


