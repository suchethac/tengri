def _make_group_figure(
    wave: np.ndarray,
    ref: dict,
    cases: list[tuple[str, str]],
    fig_title: str,
    figsize: tuple[float, float] | None = None,
) -> tuple:
    """Build a figure with one row per case, two columns (SED | residual)."""
    import matplotlib.pyplot as plt

    n = len(cases)
    fs = figsize or (13, 3.2 * n)
    fig, axes = plt.subplots(n, 2, figsize=fs, squeeze=False)
    fig.suptitle(fig_title, fontsize=11, y=1.002, fontweight="bold")

    all_stats: dict[str, dict[str, float]] = {}
    for row, (suffix, title) in enumerate(cases):
        stats = _fill_case_row(axes[row, 0], axes[row, 1], wave, ref, suffix, title)
        all_stats[suffix] = stats

    fig.tight_layout(h_pad=2.0, w_pad=2.5)
    return fig, all_stats


def _make_summary_figure(
    all_stats: dict[str, dict[str, dict[str, float]]],
    figsize: tuple[float, float] = (14, 6),
):
    """Bar chart of median |Δ| vs FSPS for tengri and bagpipes across all matched cases."""
    import matplotlib.pyplot as plt

    # Flatten: {suffix: {code: median_resid}}
    flat: dict[str, dict[str, float]] = {}
    for group_stats in all_stats.values():
        flat.update(group_stats)

    suffixes = [s for s in flat if "tengri" in flat[s]]
    if not suffixes:
        fig, ax = plt.subplots(figsize=figsize)
        ax.text(0.5, 0.5, "No matched cases", ha="center", va="center", transform=ax.transAxes)
        return fig

    x = np.arange(len(suffixes))
    w = 0.30

    tengri_vals = [flat[s].get("tengri", float("nan")) for s in suffixes]
    bags_vals = [flat[s].get("bagpipes", float("nan")) for s in suffixes]

    fig, ax = plt.subplots(figsize=figsize)
    ax.bar(x - w / 2, tengri_vals, width=w, color=_C["tengri"], alpha=0.85, label=_LABEL["tengri"])
    ax.bar(
        x + w / 2, bags_vals, width=w, color=_C["bagpipes"], alpha=0.85, label=_LABEL["bagpipes"]
    )

    # Reference tolerance lines
    ax.axhline(
        _TOL_SAME_SSP,
        color=_C["tengri"],
        lw=1.0,
        ls="--",
        alpha=0.6,
        label=f"±{int(_TOL_SAME_SSP * 100)}% (same SSP)",
    )
    ax.axhline(
        _TOL_DIFF_SSP,
        color="grey",
        lw=1.0,
        ls="--",
        alpha=0.6,
        label=f"±{int(_TOL_DIFF_SSP * 100)}% (diff. SSP)",
    )

    # Colour bar backgrounds by group
    _group_spans = [
        ("Stellar", 0, 5, "#d4e6f1"),
        ("Metallicity", 5, 9, "#d5f5e3"),
        ("Exp-τ SFH", 9, 14, "#fdebd0"),
        ("Log-normal SFH", 14, 17, "#f9ebea"),
        ("DPL SFH", 17, 20, "#f5eef8"),
    ]
    for label, i0, i1, col in _group_spans:
        if i0 >= len(suffixes):
            break
        i1 = min(i1, len(suffixes))
        ax.axvspan(i0 - 0.5, i1 - 0.5, color=col, alpha=0.35, zorder=0)
        ylim_top = ax.get_ylim()[1] if ax.get_ylim()[1] > 0 else 0.95
        ax.text(
            (i0 + i1) / 2 - 0.5,
            ylim_top * 0.95,
            label,
            ha="center",
            va="top",
            fontsize=7,
            color="black",
            alpha=0.7,
        )

    ax.set_xticks(x)
    short_labels = [
        s.replace("stellar_", "")
        .replace("expsfh_", "")
        .replace("himet_", "")
        .replace("lognorm_", "")
        .replace("dplsfh_", "")
        .replace("nebular_", "")
        for s in suffixes
    ]
    ax.set_xticklabels(short_labels, rotation=45, ha="right", fontsize=6.5)
    ax.set_ylabel("Median |Δ| = median |L_ν/L_ν^FSPS − 1|", fontsize=9)
    ax.set_title(
        "Cross-validation summary: tengri vs external codes\n"
        r"(1000–10000 Å; FSPS baseline; same MILES+Chabrier SSP ⟹ expect <25% for tengri)",
        fontsize=10,
    )
    ax.legend(fontsize=8, loc="upper left")
    ax.set_ylim(bottom=0.0)
    fig.tight_layout()
    return fig


