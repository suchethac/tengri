def _fill_case_row(
    ax_sed,
    ax_res,
    wave: np.ndarray,
    ref: dict,
    suffix: str,
    title: str,
) -> dict[str, float]:
    """Plot SED and fractional residual for one case. Returns median |Δ| per code."""
    tengri_key = f"tengri_{suffix}"
    fsps_key = f"fsps_{suffix}"
    bagpipes_key = f"bagpipes_{suffix}"
    cigale_key = f"cigale_{suffix}"

    # ── SED panel ──────────────────────────────────────────────────
    ax_sed.set_title(title, fontsize=7.5, pad=3)
    ax_sed.set_xlabel("Wavelength (Å)", fontsize=7)
    ax_sed.set_ylabel(r"$L_\nu$ [erg s$^{-1}$ Hz$^{-1}$ $M_\odot^{-1}$]", fontsize=6.5)

    plotted: list[str] = []
    for code, key, lw, zo in [
        ("fsps", fsps_key, 1.2, 2),
        ("bagpipes", bagpipes_key, 1.2, 2),
        ("cigale", cigale_key, 1.2, 2),
        ("tengri", tengri_key, 1.8, 5),
    ]:
        if key not in ref:
            continue
        sed = ref[key]
        pos = (sed > 0) & np.isfinite(sed)
        if not pos.any():
            continue
        ax_sed.semilogy(
            wave[pos], sed[pos], color=_C[code], lw=lw, alpha=0.85, label=_LABEL[code], zorder=zo
        )
        plotted.append(code)

    if plotted:
        ax_sed.set_xlim(1000, 12000)
        ax_sed.legend(fontsize=5, loc="upper right", handlelength=1.2)

    # ── Residual panel ─────────────────────────────────────────────
    ax_res.set_xlabel("Wavelength (Å)", fontsize=7)
    ax_res.set_ylabel(r"$L_\nu / L_\nu^{\rm FSPS} - 1$", fontsize=6.5)
    ax_res.axhline(0.0, color="k", lw=0.8)
    ax_res.axhspan(
        -_TOL_SAME_SSP,
        _TOL_SAME_SSP,
        color="#1f77b4",
        alpha=0.06,
        label=f"±{int(_TOL_SAME_SSP * 100)}%",
    )
    ax_res.axhspan(
        -_TOL_DIFF_SSP,
        _TOL_DIFF_SSP,
        color="grey",
        alpha=0.06,
        label=f"±{int(_TOL_DIFF_SSP * 100)}%",
    )

    stats: dict[str, float] = {}
    if fsps_key not in ref or not (ref[fsps_key] > 0).any():
        ax_res.text(
            0.5,
            0.5,
            "FSPS ref\nnot available",
            ha="center",
            va="center",
            transform=ax_res.transAxes,
            fontsize=8,
        )
        return stats

    fsps_sed = ref[fsps_key]
    fsps_safe = (fsps_sed > 0) & np.isfinite(fsps_sed)

    for code, key, lw in [
        ("bagpipes", bagpipes_key, 1.0),
        ("cigale", cigale_key, 1.0),
        ("tengri", tengri_key, 1.8),
    ]:
        if key not in ref:
            continue
        code_sed = ref[key]
        mask = fsps_safe & (code_sed > 0) & np.isfinite(code_sed)
        if not mask.any():
            continue
        resid = code_sed[mask] / fsps_sed[mask] - 1.0
        zo = 5 if code == "tengri" else 2
        ax_res.plot(
            wave[mask], resid, color=_C[code], lw=lw, alpha=0.80, label=_LABEL[code], zorder=zo
        )
        stats[code] = _median_abs_resid(code_sed, fsps_sed, wave)

    ax_res.set_xlim(1000, 12000)
    ax_res.set_ylim(-1.5, 1.5)
    ax_res.legend(fontsize=5, loc="upper right", handlelength=1.2)
    return stats


