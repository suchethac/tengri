def _resample(wave_src: np.ndarray, flux_src: np.ndarray, wave_dst: np.ndarray) -> np.ndarray:
    """Log-linear interpolation; NaN outside source range."""
    pos = flux_src > 0
    if not pos.any():
        return np.zeros(len(wave_dst))
    log_flux = np.full_like(flux_src, np.nan)
    log_flux[pos] = np.log(flux_src[pos])
    out = np.exp(
        np.interp(np.log(wave_dst), np.log(wave_src), log_flux, left=np.nan, right=np.nan)
    )
    out[(wave_dst < wave_src[0]) | (wave_dst > wave_src[-1])] = 0.0
    return out


def _median_abs_resid(
    synth: np.ndarray,
    ref: np.ndarray,
    wave: np.ndarray,
    wmin: float = 1000.0,
    wmax: float = 10000.0,
) -> float:
    """Median |synth/ref - 1| in [wmin, wmax] Å."""
    mask = (wave >= wmin) & (wave <= wmax) & (ref > 0) & np.isfinite(synth) & (synth > 0)
    if not mask.any():
        return float("nan")
    return float(np.median(np.abs(synth[mask] / ref[mask] - 1.0)))


def _plot_band_lines(ax) -> None:
    """Draw vertical reference lines at photometric band centres."""
    for band, lam in _BANDS.items():
        ax.axvline(lam, color="grey", lw=0.4, ls="--", alpha=0.35, zorder=0)
        ylims = ax.get_ylim()
        if ylims[0] > 0 and ylims[1] > 0:
            ax.text(lam, ylims[0] * 1.15, band, fontsize=4.5, ha="center", color="grey", alpha=0.7)


