def _tengri_const(
    ssp_data,
    start_gyr: float,
    end_gyr: float,
    logzsol: float = 0.0,
    tau_bc: float = 0.0,
    tau_diff: float = 0.0,
) -> tuple[np.ndarray, np.ndarray]:
    """Build tengri SED with constant SFH, return (wave_Å, L_nu per Msun_formed)."""
    import jax

    from tengri import Parameters
    from tengri.core.model import SEDModel
    from tengri.distributions import Fixed

    spec = Parameters(
        mean_sfh_type="const",
        sfh_const_log_sfr=Fixed(0.0),
        sfh_const_start_gyr=Fixed(start_gyr),
        sfh_const_end_gyr=Fixed(end_gyr),
        met_logzsol=Fixed(logzsol),
        dust_tau_bc=Fixed(tau_bc),
        dust_tau_diff=Fixed(tau_diff),
        dust_slope=Fixed(-0.7),
        redshift=0.01,
    )
    model = SEDModel(spec, ssp_data)
    params = spec.sample(jax.random.PRNGKey(0))
    result = model.predict_rest_sed(params)
    wave = np.asarray(result.wavelength)
    sed = np.asarray(result.sed)
    m_formed = (end_gyr - start_gyr) * 1.0e9  # SFR=1 Msun/yr
    return wave, sed / m_formed


def _tengri_dexp(
    ssp_data,
    tau_gyr: float,
    peak_sfr: float = 10.0,
    start_gyr: float = 0.0,
    logzsol: float = 0.0,
    tau_bc: float = 0.0,
    tau_diff: float = 0.0,
) -> tuple[np.ndarray, np.ndarray]:
    """Build tengri SED with delayed-exponential SFH, return (wave_Å, L_nu per Msun_formed)."""
    import jax

    from tengri import Parameters
    from tengri.core.model import SEDModel
    from tengri.distributions import Fixed

    spec = Parameters(
        mean_sfh_type="dexp",
        sfh_dexp_log_peak_sfr=Fixed(np.log10(peak_sfr)),
        sfh_dexp_tau_gyr=Fixed(tau_gyr),
        sfh_dexp_start_gyr=Fixed(start_gyr),
        met_logzsol=Fixed(logzsol),
        dust_tau_bc=Fixed(tau_bc),
        dust_tau_diff=Fixed(tau_diff),
        dust_slope=Fixed(-0.7),
        redshift=0.01,
    )
    model = SEDModel(spec, ssp_data)
    params = spec.sample(jax.random.PRNGKey(0))
    result = model.predict_rest_sed(params)
    wave = np.asarray(result.wavelength)
    sed = np.asarray(result.sed)
    m_formed = peak_sfr * tau_gyr * 1.0e9 * np.e  # analytic integral of t*exp(-t/tau)
    return wave, sed / m_formed


def _tengri_dpl(
    ssp_data,
    alpha: float,
    beta: float,
    tau_gyr: float,
    peak_sfr: float = 10.0,
    logzsol: float = 0.0,
    tau_bc: float = 0.0,
    tau_diff: float = 0.0,
) -> tuple[np.ndarray, np.ndarray]:
    """Build tengri SED with double-power-law SFH, return (wave_Å, L_nu per Msun_formed)."""
    import jax

    from tengri import Parameters
    from tengri.core.model import SEDModel
    from tengri.distributions import Fixed

    spec = Parameters(
        mean_sfh_type="dpl",
        sfh_dpl_log_peak_sfr=Fixed(np.log10(peak_sfr)),
        sfh_dpl_alpha=Fixed(alpha),
        sfh_dpl_beta=Fixed(beta),
        sfh_dpl_tau_gyr=Fixed(tau_gyr),
        met_logzsol=Fixed(logzsol),
        dust_tau_bc=Fixed(tau_bc),
        dust_tau_diff=Fixed(tau_diff),
        dust_slope=Fixed(-0.7),
        redshift=0.01,
    )
    model = SEDModel(spec, ssp_data)
    params = spec.sample(jax.random.PRNGKey(0))
    result = model.predict_rest_sed(params)
    wave = np.asarray(result.wavelength)
    sed = np.asarray(result.sed)
    # Numerical M_formed: integrate DPL from 0.001*tau to 100*tau Gyr
    t_yr = np.linspace(0.001 * tau_gyr, 100.0 * tau_gyr, 10000) * 1e9
    tau_yr = tau_gyr * 1e9
    sfr_t = peak_sfr / ((t_yr / tau_yr) ** alpha + (t_yr / tau_yr) ** (-beta))
    m_formed = float(np.trapz(sfr_t, t_yr))
    return wave, sed / m_formed


def _build_all_tengri_seds(ssp_data, ref_wave: np.ndarray) -> dict[str, np.ndarray]:
    """Build tengri SEDs for all matched cases and resample to ref_wave.

    Returns dict mapping 'tengri_{suffix}' → resampled SED per Msun (erg/s/Hz).
    Cases without a tengri implementation are silently skipped:
    - nebular: requires a separate SSP file with ionising photons
    - expsfh:  FSPS/bagpipes use a DECLINING tau model (SFR peaks at galaxy formation,
               falls toward the present — highest SFR at early cosmic times). tengri's
               SFH types use lookback-time parameterization where 'exp' and 'dexp' both
               represent SFHs that are most active in the RECENT past. There is no
               direct declining-tau equivalent in tengri's current SFH registry.
               Cross-validating expsfh would compare different physical galaxy types
               (old quenched vs. recently star-forming), not code differences.
               See docs/known_bugs.md CROSSVAL-02.
    """
    print("Building tengri SEDs live (this takes ~30–60 s for JIT compilation)...")
    seds: dict[str, np.ndarray] = {}

    def _add(suffix: str, wave: np.ndarray, sed_per_msun: np.ndarray) -> None:
        seds[f"tengri_{suffix}"] = _resample(wave, sed_per_msun, ref_wave)
        print(f"  tengri_{suffix}: OK")

    # ── Stellar cases (constant SFH) ─────────────────────────────────────
    _add("stellar_starforming", *_tengri_const(ssp_data, 0.0, 3.0))
    _add("stellar_old_quenched", *_tengri_const(ssp_data, 5.0, 10.0))
    _add("stellar_dusty_sfg", *_tengri_const(ssp_data, 0.0, 3.0, tau_bc=1.0, tau_diff=0.5))
    _add("stellar_metal_poor", *_tengri_const(ssp_data, 0.0, 5.0, logzsol=-1.0))
    _add("stellar_metal_rich", *_tengri_const(ssp_data, 0.0, 5.0, logzsol=0.2))

    # ── Metallicity cases (constant SFH) ─────────────────────────────────
    _add("himet_zsun", *_tengri_const(ssp_data, 0.0, 5.0))
    _add("himet_z0p2", *_tengri_const(ssp_data, 0.0, 5.0, logzsol=0.2))
    _add("himet_z_neg1", *_tengri_const(ssp_data, 0.0, 5.0, logzsol=-1.0))
    _add("himet_z_neg2", *_tengri_const(ssp_data, 0.0, 8.0, logzsol=-2.0))

    # ── Exp-τ cases: SKIPPED for tengri ──────────────────────────────────
    # FSPS/bagpipes use a declining tau model (SFR highest at galaxy formation,
    # declining to present in cosmic time). This corresponds to SFR INCREASING
    # with lookback time in DSPS convention — the opposite of tengri's 'exp' SFH.
    # tengri's 'dexp' (delayed tau) peaks at start+tau in lookback time, representing
    # a recently star-forming galaxy, not a galaxy formed long ago.
    # Comparing them would show SFH-shape mismatch, not code errors.
    # See CROSSVAL-02 in docs/known_bugs.md.
    # (no lines added — tengri_{expsfh_*} keys intentionally absent)

    # ── Log-normal cases (dexp approximation: matched peak lookback time) ──
    # FSPS lognorm_early: peak at 2 Gyr from BB, tage=10 Gyr → peak 8 Gyr ago
    # tengri dexp: start=7 Gyr + tau=1 Gyr → peak also 8 Gyr lookback
    _add("lognorm_lognorm_early", *_tengri_dexp(ssp_data, tau_gyr=1.0, start_gyr=7.0))
    # FSPS lognorm_recent: peak at 1 Gyr from BB, tage=5 Gyr → peak 4 Gyr ago
    _add("lognorm_lognorm_recent", *_tengri_dexp(ssp_data, tau_gyr=0.5, start_gyr=3.0))
    # FSPS lognorm_broad: peak at 3.5 Gyr from BB, tage=8 Gyr → peak 4.5 Gyr ago
    _add("lognorm_lognorm_broad", *_tengri_dexp(ssp_data, tau_gyr=2.0, start_gyr=4.0))

    # ── DPL cases ──────────────────────────────────────────────────────────
    _add(
        "dplsfh_dpl_alpha5_beta5",
        *_tengri_dpl(ssp_data, alpha=5.0, beta=5.0, tau_gyr=3.0),
    )
    _add(
        "dplsfh_dpl_alpha10_beta2",
        *_tengri_dpl(ssp_data, alpha=10.0, beta=2.0, tau_gyr=2.0),
    )
    _add(
        "dplsfh_dpl_alpha3_beta10_dusty",
        *_tengri_dpl(
            ssp_data,
            alpha=3.0,
            beta=10.0,
            tau_gyr=4.0,
            logzsol=-0.5,
            tau_bc=0.8,
            tau_diff=0.3,
        ),
    )

    # Nebular cases are intentionally skipped — tengri's nebular cross-validation
    # requires a separate SSP file with ionising photons; no direct comparison is
    # included in the test suite.
    print(f"  Built {len(seds)} tengri SEDs.")
    return seds


