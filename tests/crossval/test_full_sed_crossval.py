    def test_fsps_tabsfh_seds_finite(self, ref, ref_wave):
        for name in self._CASES:
            key = f"fsps_tabsfh_{name}"
            if key not in ref:
                pytest.skip(f"Key {key!r} not in npz — FSPS not available")
            assert np.all(np.isfinite(ref[key])), f"NaN/Inf in {key}"
            assert np.all(ref[key] >= 0.0), f"Negative flux in {key}"

    def test_rising_sfh_bluer_than_quenching(self, ref, ref_wave):
        """Rising SFH (high current SFR) should be bluer than quenching SFH.

        step_rising: sfr_per_bin = [5.0, 2.0, 0.8, 0.2] Msun/yr (young → old)
          → high recent SFR → many young stars → blue UV.
        step_quenching: sfr_per_bin = [0.2, 1.0, 3.0, 5.0]
          → low recent SFR → few young stars → red UV.
        """
        k_rise = "fsps_tabsfh_step_rising"
        k_quench = "fsps_tabsfh_step_quenching"
        if k_rise not in ref or k_quench not in ref:
            pytest.skip("Both step_rising and step_quenching needed")

        v_idx = np.argmin(np.abs(ref_wave - 5500.0))
        uv_idx = np.argmin(np.abs(ref_wave - 2800.0))

        color_rise = ref[k_rise][uv_idx] / ref[k_rise][v_idx]
        color_quench = ref[k_quench][uv_idx] / ref[k_quench][v_idx]
        assert color_rise > color_quench, (
            f"Rising SFH UV/V ({color_rise:.3f}) not greater than quenching ({color_quench:.3f}). "
            "Step-function SFH assignment (searchsorted) may be inverted."
        )

    def test_bursty_sfh_has_high_uv(self, ref, ref_wave):
        """Bursty SFH with strong recent burst should have elevated UV emission.

        step_bursty: sfr_per_bin = [8.0, 0.5, 2.0, 0.3] Msun/yr — very high recent SFR.
        UV/V ratio should be at least as high as the quenching case.
        """
        k_bursty = "fsps_tabsfh_step_bursty"
        k_quench = "fsps_tabsfh_step_quenching"
        if k_bursty not in ref or k_quench not in ref:
            pytest.skip("step_bursty and step_quenching needed")

        v_idx = np.argmin(np.abs(ref_wave - 5500.0))
        uv_idx = np.argmin(np.abs(ref_wave - 2800.0))
        color_bursty = ref[k_bursty][uv_idx] / ref[k_bursty][v_idx]
        color_quench = ref[k_quench][uv_idx] / ref[k_quench][v_idx]
        assert color_bursty > color_quench, (
            f"Bursty SFH UV/V ({color_bursty:.3f}) not higher than quenching "
            f"({color_quench:.3f}). Recent burst (sfr=8 Msun/yr) should dominate UV emission."
        )

    def test_tengri_nonparametric_colour_trend(self, ssp_data):
        """tengri continuity_sfh: rising SFH should be bluer than quenching SFH.

        This checks the tengri implementation independently of FSPS.
        Uses the same SFR-per-bin values as TABSFH_CASES in the reference generator.
        """
        try:
            from tengri.models.sfh.nonparametric import continuity_sfh
        except ImportError:
            pytest.skip("continuity_sfh not importable")

        bin_edges = jnp.array([0.0, 0.1, 0.5, 2.0, 6.0])
        sfr_rising = jnp.array([5.0, 2.0, 0.8, 0.2])
        sfr_quenching = jnp.array([0.2, 1.0, 3.0, 5.0])

        wave = jnp.asarray(ssp_data.ssp_wave)

        def uv_over_v(sfr_bins):
            t_obs, sfr_t = continuity_sfh(bin_edges, sfr_bins, n_pts=200)
            # Compute CSP: approximate as sum of SSPs weighted by SFR dt
            from tengri.models.sps.dsps_wrapper import compute_csp_weights

            weights = compute_csp_weights(t_obs, sfr_t)
            sed = jnp.einsum("t,tw->w", weights, ssp_data.ssp_flux[0])  # solar Z
            v = float(jnp.mean(sed[(wave > 5400.0) & (wave < 5600.0)]))
            uv = float(jnp.mean(sed[(wave > 2700.0) & (wave < 2900.0)]))
            return uv / max(v, 1e-30)

        try:
            cr = uv_over_v(sfr_rising)
            cq = uv_over_v(sfr_quenching)
        except Exception as exc:
            pytest.skip(f"continuity_sfh computation failed: {exc}")

        assert cr > cq, (
            f"tengri rising SFH UV/V ({cr:.3f}) not greater than quenching ({cq:.3f}). "
            "Check searchsorted bin assignment in continuity_sfh."
        )


