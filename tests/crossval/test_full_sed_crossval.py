class TestDustySFG:
    """Tengri vs external codes: 3 Gyr constant SFH + CF00 dust."""

    @pytest.fixture(scope="class")
    def tengri_clean(self, ssp_data):
        _, sed, _ = _build_tengri_sed(ssp_data, start_gyr=0.0, end_gyr=3.0)
        return sed

    @pytest.fixture(scope="class")
    def tengri_dusty(self, ssp_data):
        _, sed, _ = _build_tengri_sed(
            ssp_data,
            start_gyr=0.0,
            end_gyr=3.0,
            tau_bc=1.0,
            tau_diff=0.5,
            dust_slope=-0.7,
        )
        return sed

    def test_tengri_vs_fsps_vband(self, tengri_dusty, ref, ref_wave, ssp_data):
        """V-band luminosity per Msun within 15% of FSPS (dusty; tau_bc=1.0, tau_diff=0.5).

        Same SSPs + same CF00 dust parameters. 15% allows for tau→Av conversion
        rounding; tighter failure implies a CF00 dust1/dust2 mapping bug.
        """
        key = "fsps_stellar_dusty_sfg"
        if key not in ref:
            pytest.skip(f"Reference key {key!r} not in npz")

        wave = np.asarray(ssp_data.ssp_wave)
        l_tengri = _band_avg(wave, tengri_dusty, 5500.0)
        l_fsps = _band_avg(ref_wave, ref[key], 5500.0)

        ratio = l_tengri / l_fsps
        assert 0.85 <= ratio <= 1.15, (
            f"V-band L_nu/Msun ratio tengri/FSPS = {ratio:.3f} (dusty_sfg). "
            f"tengri={l_tengri:.3e}, fsps={l_fsps:.3e} erg/s/Hz/Msun. "
            "tau_bc=1.0→dust1=1.086, tau_diff=0.5→dust2=0.543. Check 1.086 factor."
        )

    def test_dust_attenuates_uv_more_than_optical(self, tengri_clean, tengri_dusty, ssp_data):
        """Dust should reduce UV (2800 Å) more than V-band (5500 Å).

        CF00 has a steeper attenuation law in the UV, so the UV/V ratio should
        decrease when dust is added. If UV attenuation is *less* than optical,
        the dust law slope or normalisation is implemented backwards.
        """
        wave = np.asarray(ssp_data.ssp_wave)

        uv_clean = _band_avg(wave, tengri_clean, 2800.0, half_width=150.0)
        uv_dusty = _band_avg(wave, tengri_dusty, 2800.0, half_width=150.0)
        v_clean = _band_avg(wave, tengri_clean, 5500.0)
        v_dusty = _band_avg(wave, tengri_dusty, 5500.0)

        uv_suppression = uv_dusty / uv_clean
        v_suppression = v_dusty / v_clean

        assert uv_suppression < v_suppression, (
            f"UV suppression ({uv_suppression:.3f}) is NOT stronger than "
            f"V-band suppression ({v_suppression:.3f}). "
            "CF00 dust slope bug: UV should always be more attenuated than optical."
        )

    def test_dust_reduces_vband_flux(self, tengri_clean, tengri_dusty, ssp_data):
        """Dust must reduce V-band flux (tau_diff=0.5 ↔ ~0.54 mag at V)."""
        wave = np.asarray(ssp_data.ssp_wave)
        v_clean = _band_avg(wave, tengri_clean, 5500.0)
        v_dusty = _band_avg(wave, tengri_dusty, 5500.0)

        suppression = v_dusty / v_clean
        # tau_diff=0.5: extinction = exp(-0.5) ≈ 0.61; expect 0.4–0.8
        assert 0.40 <= suppression <= 0.80, (
            f"V-band dust suppression = {suppression:.3f}; "
            f"expected 0.40–0.80 for tau_diff=0.5. "
            "Possible: wrong CF00 Av convention (Av vs tau) or wrong factor of 1.086."
        )

    def test_tengri_vs_bagpipes_vband(self, tengri_dusty, ref, ref_wave, ssp_data):
        """Dusty V-band within factor 2.5 of bagpipes (different SSPs + dust treatment)."""
        key = "bagpipes_stellar_dusty_sfg"
        if key not in ref:
            pytest.skip(f"Reference key {key!r} not in npz")

        wave = np.asarray(ssp_data.ssp_wave)
        l_tengri = _band_avg(wave, tengri_dusty, 5500.0)
        l_bagpipes = _band_avg(ref_wave, ref[key], 5500.0)

        ratio = l_tengri / l_bagpipes
        # Wider tolerance: BC03 vs MILES + slightly different CF00 Av convention
        assert 0.4 <= ratio <= 2.5, (
            f"V-band L_nu/Msun ratio tengri/bagpipes = {ratio:.3f} (dusty_sfg). "
            f"tengri={l_tengri:.3e}, bagpipes={l_bagpipes:.3e} erg/s/Hz/Msun."
        )


