class TestNebularEmission:
    """Cross-validate nebular line + continuum emission.

    Both codes use CLOUDY pre-tabulated grids (bagpipes: BC03+CLOUDY; FSPS: its
    own nebular tables). Checks: lines present, logU trend, inter-code agreement.
    """

    _CASES = ("neb_young_u2", "neb_young_u35", "neb_dusty_u25")

    def test_fsps_nebular_seds_finite(self, ref, ref_wave):
        for name in self._CASES:
            key = f"fsps_nebular_{name}"
            if key not in ref:
                pytest.skip(f"Key {key!r} not in npz")
            assert np.all(np.isfinite(ref[key])), f"NaN/Inf in {key}"
            assert np.all(ref[key] >= 0.0), f"Negative flux in {key}"

    def test_bagpipes_nebular_seds_finite(self, ref, ref_wave):
        for name in self._CASES:
            key = f"bagpipes_nebular_{name}"
            if key not in ref:
                pytest.skip(f"Key {key!r} not in npz")
            assert np.all(np.isfinite(ref[key])), f"NaN/Inf in {key}"
            assert np.all(ref[key] >= 0.0), f"Negative flux in {key}"

    def test_higher_logu_means_more_uv_emission(self, ref, ref_wave):
        """Higher ionization parameter (logU=-2 vs -3.5) should produce more UV/optical emission.

        logU controls the ionization state — higher logU = harder radiation field
        = stronger line emission across UV and optical.
        """
        for code in ("bagpipes", "fsps"):
            ku2 = f"{code}_nebular_neb_young_u2"
            ku35 = f"{code}_nebular_neb_young_u35"
            if ku2 not in ref or ku35 not in ref:
                continue
            # Hα at ~6565 Å (strongest optical line) should be stronger at higher logU
            ha_u2 = _band_avg(ref_wave, ref[ku2], 6563.0, half_width=30.0)
            ha_u35 = _band_avg(ref_wave, ref[ku35], 6563.0, half_width=30.0)
            # Hα is a recombination line set by total ionizing photon count,
            # not logU directly. Allow ±1% as the sign can vary slightly.
            assert ha_u2 >= ha_u35 * 0.99, (
                f"[{code}] logU=-2 Hα ({ha_u2:.3e}) is >1% below logU=-3.5 ({ha_u35:.3e}). "
                f"CLOUDY logU convention inverted?"
            )

    def test_fsps_bagpipes_vband_agreement(self, ref, ref_wave):
        """V-band (5500 Å) agreement within factor 3 between bagpipes and FSPS.

        Nebular continuum contribution + different CLOUDY grids allow wider tolerance.
        """
        kf = "fsps_nebular_neb_young_u2"
        kb = "bagpipes_nebular_neb_young_u2"
        if kf not in ref or kb not in ref:
            pytest.skip("Both FSPS and bagpipes nebular SEDs needed")

        l_fsps = _band_avg(ref_wave, ref[kf], 5500.0)
        l_bp = _band_avg(ref_wave, ref[kb], 5500.0)
        ratio = l_fsps / l_bp
        assert 0.33 <= ratio <= 3.0, (
            f"FSPS/bagpipes V-band ratio (neb_young_u2) = {ratio:.3f} (expect 0.33–3.0). "
            f"FSPS={l_fsps:.3e}, bagpipes={l_bp:.3e} erg/s/Hz/Msun."
        )


# ── Nebular emission — tengri pipeline (CLOUDY grid) ──────────────


def _build_tengri_nebular_sed(
    ssp_data,
    age_gyr: float = 0.1,
    logzsol: float = 0.0,
    logU: float = -2.0,
    tau_bc: float = 0.0,
    tau_diff: float = 0.0,
    log_sfr: float = 1.0,
) -> tuple[np.ndarray, np.ndarray]:
    """Build tengri SED with nebular emission via the CLOUDY pdva grid.

    Returns (wave_Å, L_nu per Msun formed in erg/s/Hz).
    Galaxy is a constant-SFR burst of duration age_gyr at SFR = 10^log_sfr Msun/yr.

    ``sfh_const_log_total_mass`` is a **total mass**, not a rate. It was being
    handed ``log_sfr`` directly, so the SED described a galaxy of 10 Msun and
    was then divided by an m_formed of 1e9 — low by eight orders of magnitude,
    which is the "ratio tengri/FSPS = 0.000" this file reported (#1728). Same
    mix-up as `_build_tengri_sed` above; the mass is derived from the requested
    SFR and duration.
    """
    from tengri import Parameters
    from tengri.forward.sed_model import SEDModel
    from tengri.parameters.priors import Fixed

    sfr = 10.0**log_sfr
    m_formed = sfr * age_gyr * 1e9  # Msun

    spec = Parameters(
        mean_sfh_type="const",
        nebular="cloudy",
        cloudy_grid_path="data/cloudy_grid_pdva.h5",
        met_logzsol=Fixed(logzsol),
        sfh_const_start_gyr=Fixed(age_gyr),
        sfh_const_end_gyr=Fixed(0.0),
        sfh_const_log_total_mass=Fixed(float(np.log10(m_formed))),
        neb_logU=Fixed(logU),
        neb_logZ_gas=Fixed(logzsol),
        dust_tau_bc=Fixed(tau_bc),
        dust_tau_diff=Fixed(tau_diff),
        dust_slope=Fixed(-0.7),
        redshift=0.01,
    )
    model = SEDModel(spec, ssp_data)
    params = spec.sample(jax.random.PRNGKey(0))
    result = model.predict_rest_sed(params)
    wave = np.asarray(result.wavelength)
    sed = np.asarray(result.sed)
    return wave, sed / m_formed


def _line_peak(
    wave: np.ndarray, sed: np.ndarray, center_aa: float, half_width: float = 50.0
) -> float:
    """Max flux in a ±half_width Å window around center_aa (for emission line amplitude)."""
    mask = np.abs(wave - center_aa) <= half_width
    return float(np.max(sed[mask])) if mask.any() else 0.0


def _line_flux(
    wave: np.ndarray,
    sed_nu: np.ndarray,
    center_aa: float,
    half_width: float = 120.0,
    cont_half_width: float = 400.0,
) -> float:
    """Continuum-subtracted integrated line flux [erg/s per Msun].

    Peak height is not comparable between codes: it depends on how finely each
    one renders the line. The FSPS reference grid carries 7 points across
    +/-120 A of Halpha (~33 A spacing, the line unresolved) where tengri's
    carries 267, so the same line flux appears as an 8.7x difference in peak
    and a 2.1x difference when integrated. Integrating in frequency, with a
    local linear continuum removed from the side bands, is resolution-
    independent and is what "how much Halpha" actually means (#1728).
    """
    near = np.abs(wave - center_aa) <= half_width
    side = (np.abs(wave - center_aa) > half_width) & (np.abs(wave - center_aa) <= cont_half_width)
    if near.sum() < 2 or side.sum() < 2:
        return 0.0

    continuum = np.interp(wave[near], wave[side], sed_nu[side])
    nu = _C_AA / wave[near]
    order = np.argsort(nu)
    return abs(float(np.trapezoid((sed_nu[near] - continuum)[order], nu[order])))


