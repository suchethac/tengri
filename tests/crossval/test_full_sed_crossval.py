    def test_dpl_vs_fsps_vband_order_of_magnitude(self, ssp_data, ref, ref_wave):
        """DPL V-band within order of magnitude of FSPS constant SFH per Msun.

        DPL and constant SFH produce different SED shapes, but absolute luminosity
        per Msun should be within 10x at V-band for physically similar galaxies.
        """
        key = "fsps_stellar_starforming"
        if key not in ref:
            pytest.skip(f"Reference key {key!r} not in npz")

        # Rough M_formed estimate for DPL (alpha=1.5, beta=5, tau=3 Gyr, peak=10 Msun/yr):
        # Numerical integration; approximate ≈ peak_sfr × tau × B(1+1/alpha, 1+1/beta)
        # For simplicity, use tau × peak_sfr × 2 as rough estimate
        peak_sfr = 10.0
        tau_gyr = 3.0
