    def test_dpl_steep_fall_is_redder_than_rising(self, ssp_data):
        """DPL with steep fall (high beta) should be redder than gently falling (low beta).

        High beta = rapid quenching after peak → fewer young stars → redder UV.
        """
        _wave_steep, sed_steep = _build_tengri_sed_raw(
            ssp_data,
            "dpl",
            {
                "sfh_dpl_log_peak_sfr": 1.0,
                "sfh_dpl_alpha": 1.5,
                "sfh_dpl_beta": 20.0,
                "sfh_dpl_tau_gyr": 3.0,
            },
        )
        _wave_gentle, sed_gentle = _build_tengri_sed_raw(
            ssp_data,
            "dpl",
            {
                "sfh_dpl_log_peak_sfr": 1.0,
                "sfh_dpl_alpha": 1.5,
                "sfh_dpl_beta": 1.5,
                "sfh_dpl_tau_gyr": 3.0,
            },
        )
        w = np.asarray(ssp_data.ssp_wave)

