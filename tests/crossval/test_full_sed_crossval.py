# Helper: band-averaged flux
# ---------------------------------------------------------------------------


def _band_avg(
    wave: np.ndarray, flux: np.ndarray, center: float, half_width: float = 100.0
) -> float:
    """Return mean flux in [center - half_width, center + half_width] Angstrom."""
    mask = (wave > center - half_width) & (wave < center + half_width)
    if not mask.any():
        raise ValueError(f"No wavelength coverage at {center} Å")
    return float(np.nanmean(flux[mask]))


def _build_tengri_sed(
    ssp_data,
    start_gyr: float,
    end_gyr: float,
    logzsol: float = 0.0,
    tau_bc: float = 0.0,
    tau_diff: float = 0.0,
    dust_slope: float = -0.7,
) -> tuple[np.ndarray, np.ndarray, float]:
    """Build tengri SED and return (wave_Å, L_nu_per_Msun_erg/s/Hz, m_formed_Msun).

    Uses log_sfr=0.0 (SFR = 1 Msun/yr) so M_formed = (end-start) * 1e9 Msun.
    SED is divided by M_formed to give erg/s/Hz per Msun.
    """
    from tengri import Parameters
    from tengri.core.model import SEDModel
    from tengri.distributions import Fixed

    spec = Parameters(
        mean_sfh_type="const",
        sfh_const_log_sfr=Fixed(0.0),  # SFR = 1 Msun/yr
        sfh_const_start_gyr=Fixed(start_gyr),
        sfh_const_end_gyr=Fixed(end_gyr),
        met_logzsol=Fixed(logzsol),
        dust_tau_bc=Fixed(tau_bc),
        dust_tau_diff=Fixed(tau_diff),
        dust_slope=Fixed(dust_slope),
        redshift=0.01,
    )
    model = SEDModel(spec, ssp_data)
    params = spec.sample(jax.random.PRNGKey(0))

    # predict_rest_sed returns SEDResult(wavelength=..., sed=...) — a NamedTuple
    result = model.predict_rest_sed(params)
    wave = np.asarray(result.wavelength)  # Å
    sed_total = np.asarray(result.sed)  # erg/s/Hz (total for all stars formed)

    m_formed = (end_gyr - start_gyr) * 1.0e9  # Msun (SFR = 1 Msun/yr)
    sed_per_msun = sed_total / m_formed  # erg/s/Hz per Msun
    return wave, sed_per_msun, m_formed


