class TestColourTrends:
    """Cross-case SED shapes must obey physically expected colour trends."""

    def test_starforming_is_bluer_than_quenched(self, ssp_data):
        """UV/V ratio must be higher for star-forming than quenched galaxy.

        This is a fundamental prediction of stellar evolution. If this fails,
        the SFH implementation (constant vs truncated) is broken.
        """
        _, sf_sed, _ = _build_tengri_sed(ssp_data, start_gyr=0.0, end_gyr=3.0)
        _, qu_sed, _ = _build_tengri_sed(ssp_data, start_gyr=5.0, end_gyr=10.0)
        wave = np.asarray(ssp_data.ssp_wave)

        sf_color = _band_avg(wave, sf_sed, 2800.0, half_width=200.0) / _band_avg(
            wave, sf_sed, 5500.0
        )
        qu_color = _band_avg(wave, qu_sed, 2800.0, half_width=200.0) / _band_avg(
            wave, qu_sed, 5500.0
        )

        assert sf_color > qu_color, (
            f"Star-forming UV/V ({sf_color:.3f}) not higher than quenched ({qu_color:.3f}). "
            "SFH age-weighting likely incorrect."
        )

    def test_dust_reddens_galaxy(self, ssp_data):
        """Dusty SFG must be redder (lower UV/V) than clean SFG."""
        _, sf_clean, _ = _build_tengri_sed(ssp_data, start_gyr=0.0, end_gyr=3.0)
        _, sf_dusty, _ = _build_tengri_sed(
            ssp_data, start_gyr=0.0, end_gyr=3.0, tau_bc=1.0, tau_diff=0.5
        )
        wave = np.asarray(ssp_data.ssp_wave)

        clean_color = _band_avg(wave, sf_clean, 2800.0, half_width=200.0) / _band_avg(
            wave, sf_clean, 5500.0
        )
        dusty_color = _band_avg(wave, sf_dusty, 2800.0, half_width=200.0) / _band_avg(
            wave, sf_dusty, 5500.0
        )

        assert dusty_color < clean_color, (
            f"Dusty SFG is NOT redder than clean SFG: "
            f"dusty UV/V = {dusty_color:.3f}, clean UV/V = {clean_color:.3f}. "
            "CF00 dust is not reducing UV more than V-band — direction bug."
        )

    def test_all_codes_agree_on_colour_trend(self, ref, ref_wave):
        """bagpipes, FSPS, and CIGALE should all show starforming is bluer than quenched."""
        for code in ("bagpipes", "fsps", "cigale"):
            sf_key = f"{code}_stellar_starforming"
            qu_key = f"{code}_stellar_old_quenched"
            if sf_key not in ref or qu_key not in ref:
                continue  # skip if this code was not available

            sf_uv = _band_avg(ref_wave, ref[sf_key], 2800.0, half_width=200.0)
            sf_v = _band_avg(ref_wave, ref[sf_key], 5500.0)
            qu_uv = _band_avg(ref_wave, ref[qu_key], 2800.0, half_width=200.0)
            qu_v = _band_avg(ref_wave, ref[qu_key], 5500.0)

            sf_color = sf_uv / sf_v
            qu_color = qu_uv / qu_v

            assert sf_color > qu_color, (
                f"[{code}] Star-forming UV/V ({sf_color:.3f}) not greater than "
                f"quenched UV/V ({qu_color:.3f}). Bug in {code} reference generator."
            )


