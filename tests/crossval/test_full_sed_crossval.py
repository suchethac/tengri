class TestIGMAttenuation:
    """Cross-validate IGM attenuation (Inoue 2014) from FSPS.

    Reference pairs: `fsps_igm_{name}` (with IGM) and `fsps_igm_{name}_noigm`
    (same galaxy, IGM disabled). The difference quantifies the IGM contribution.

    tengri: `igm_transmission(wave_obs, z)` takes observed-frame wavelengths.
    """

    _CASES = ("highz_z2", "highz_z3", "highz_z5")

    def test_fsps_igm_seds_finite(self, ref, ref_wave):
        for name in self._CASES:
            for suffix in ("", "_noigm"):
                key = f"fsps_igm_{name}{suffix}"
                if key not in ref:
                    continue
                assert np.all(np.isfinite(ref[key])), f"NaN/Inf in {key}"
                assert np.all(ref[key] >= 0.0), f"Negative flux in {key}"

    def test_igm_attenuates_uv(self, ref, ref_wave):
        """IGM must attenuate flux shortward of Lyman-alpha (1216 Å rest) by >50%.

        At z=2, Lyα is observed at 3648 Å. Blueward of Lyα, the IGM Lyman series
        absorbs strongly. The mean transmission at wavelengths 1000–3500 Å (obs)
        at z=2 should be <50% of the no-IGM case (Inoue 2014 predicts near-zero
        below Lyman limit). This is a tight check — if it fails, the IGM model
        is essentially switched off or the Lyman-series opacity is missing.
        """
        zred_map = {"highz_z2": 2.0, "highz_z3": 3.0, "highz_z5": 5.0}
        lya_rest = 1216.0

        for name, zred in zred_map.items():
            key_igm = f"fsps_igm_{name}"
            key_noigm = f"fsps_igm_{name}_noigm"
            if key_igm not in ref or key_noigm not in ref:
                continue

            lya_obs = lya_rest * (1.0 + zred)
            # Check suppression in a band clearly blueward of Lyα
            blue_of_lya = (ref_wave > 1000.0) & (ref_wave < lya_obs - 200.0)
            if not blue_of_lya.any():
                continue

            flux_igm = np.mean(ref[key_igm][blue_of_lya])
            flux_noigm = np.mean(ref[key_noigm][blue_of_lya])

            if flux_noigm < 1e-40:
                continue

            igm_transmission = flux_igm / flux_noigm
            # Inoue 2014: at z=2 the mean transmission blueward of Lyα is <50%;
            # at z=3 and z=5 it approaches zero below the Lyman limit.
            assert igm_transmission < 0.5, (
                f"[{name}] IGM transmission blueward of Lyα = {igm_transmission:.3f} "
                f"(expect <0.5). IGM absorption appears too weak or disabled."
            )

    def test_tengri_igm_vs_fsps(self, ssp_data, ref, ref_wave):
        """tengri igm_transmission (Inoue 2014) matches FSPS (also Inoue 2014) within 10%.

        Both implement the same Inoue (2014) LAF+DLA opacity table. The ratio of
        IGM-attenuated / no-IGM flux at a given observed wavelength should be
        identical between tengri and FSPS for z=2. This is a pure opacity comparison,
        independent of SSP library differences.
        """
        key_igm = "fsps_igm_highz_z2"
        key_noigm = "fsps_igm_highz_z2_noigm"
        if key_igm not in ref or key_noigm not in ref:
            pytest.skip("IGM z=2 reference pair not in npz")

        try:
            from tengri.models.igm import igm_transmission
        except ImportError:
            pytest.skip("tengri igm_transmission not importable")

        zred = 2.0
        # Compare IGM transmission at 2000 Å observed (rest 667 Å — deep in Lyman series)
        obs_band = (ref_wave > 1800.0) & (ref_wave < 2200.0)
        if not obs_band.any():
            pytest.skip("No coverage at 2000 Å observed in wave_grid")

        fsps_trans = np.mean(ref[key_igm][obs_band]) / max(
            np.mean(ref[key_noigm][obs_band]), 1e-40
        )

        # tengri: evaluate transmission at observed-frame wavelengths
        wave_obs_test = ref_wave[obs_band]
        tengri_trans_arr = np.array([float(igm_transmission(w, zred)) for w in wave_obs_test])
        tengri_trans = float(np.mean(tengri_trans_arr))

        # Both should give the same Inoue 2014 transmission; allow 10% residual
        if abs(fsps_trans) < 1e-6:
            pytest.skip("FSPS IGM reference has essentially zero transmission here — skip")

        ratio = tengri_trans / fsps_trans
        assert 0.90 <= ratio <= 1.10, (
            f"tengri/FSPS IGM transmission ratio at 2000 Å (z=2) = {ratio:.3f} "
            f"(expect 0.90–1.10). tengri T={tengri_trans:.4f}, FSPS T={fsps_trans:.4f}. "
            "Both use Inoue 2014 — discrepancy indicates LAF/DLA opacity table mismatch."
        )

    def test_higher_redshift_stronger_igm_suppression(self, ref, ref_wave):
        """Higher redshift → more IGM path length → stronger Lyman-series absorption.

        Compare z=2 vs z=3: UV suppression (normalized by no-IGM flux) should be
        stronger at z=3 (more IGM column along the line of sight).
        """
        key_z2 = "fsps_igm_highz_z2"
        key_z2_noigm = "fsps_igm_highz_z2_noigm"
        key_z3 = "fsps_igm_highz_z3"
        key_z3_noigm = "fsps_igm_highz_z3_noigm"
        if not all(k in ref for k in (key_z2, key_z2_noigm, key_z3, key_z3_noigm)):
            pytest.skip("Need both z=2 and z=3 IGM cases")

        # Compare at 2000 Å observed (rest-frame 667 Å at z=2, 500 Å at z=3 — Lyman series)
        obs_band = (ref_wave > 1800.0) & (ref_wave < 2200.0)
        if not obs_band.any():
            pytest.skip("No coverage at 2000 Å in wave_grid")

        sup_z2 = np.mean(ref[key_z2][obs_band]) / max(np.mean(ref[key_z2_noigm][obs_band]), 1e-40)
        sup_z3 = np.mean(ref[key_z3][obs_band]) / max(np.mean(ref[key_z3_noigm][obs_band]), 1e-40)

        assert sup_z3 <= sup_z2, (
            f"z=3 IGM suppression ({sup_z3:.3f}) not stronger than z=2 ({sup_z2:.3f}). "
            "Higher redshift should accumulate more IGM opacity at fixed observed wavelength."
        )


