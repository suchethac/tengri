class TestStarforming:
    """Tengri vs external codes: 3 Gyr constant SFH, solar Z, no dust."""

    @pytest.fixture(scope="class")
    def tengri(self, ssp_data):
        wave, sed_per_msun, m_formed = _build_tengri_sed(ssp_data, start_gyr=0.0, end_gyr=3.0)
        return {"wave": wave, "sed": sed_per_msun, "m_formed": m_formed}

    def test_tengri_vs_fsps_vband(self, tengri, ref, ref_wave):
        """V-band (5500 Å) luminosity per Msun within 10% of FSPS.

        Same SSP library (MILES, Chabrier), same SFH (3 Gyr const), same IMF.
        Residual from CSP trapezoidal quadrature vs FSPS internal integration.
        Tighter than 10% is expected; failure indicates a CSP weight or unit bug.
        """
        key = "fsps_stellar_starforming"
        if key not in ref:
            pytest.skip(f"Reference key {key!r} not in npz (FSPS not installed?)")

        l_tengri = _band_avg(tengri["wave"], tengri["sed"], 5500.0)
        l_fsps = _band_avg(ref_wave, ref[key], 5500.0)

        ratio = l_tengri / l_fsps
        assert 0.90 <= ratio <= 1.10, (
            f"V-band L_nu/Msun ratio tengri/FSPS = {ratio:.3f} (expect 0.90–1.10). "
            f"tengri={l_tengri:.3e}, fsps={l_fsps:.3e} erg/s/Hz/Msun. "
            "Both use MILES+Chabrier SSPs, 3 Gyr const SFH. Failure → CSP weight bug, "
            "wrong M_formed, or unit conversion error."
        )

    def test_tengri_vs_fsps_nuv(self, tengri, ref, ref_wave):
        """NUV (2800 Å) luminosity per Msun within 20% of FSPS.

        Same SSPs. UV is more sensitive to metallicity interpolation scheme and
        TP-AGB treatment; 20% is the physically motivated target.
        """
        key = "fsps_stellar_starforming"
        if key not in ref:
            pytest.skip(f"Reference key {key!r} not in npz")

        l_tengri = _band_avg(tengri["wave"], tengri["sed"], 2800.0, half_width=150.0)
        l_fsps = _band_avg(ref_wave, ref[key], 2800.0, half_width=150.0)

        ratio = l_tengri / l_fsps
        assert 0.80 <= ratio <= 1.20, (
            f"NUV L_nu/Msun ratio tengri/FSPS = {ratio:.3f} (expect 0.80–1.20). "
            f"tengri={l_tengri:.3e}, fsps={l_fsps:.3e} erg/s/Hz/Msun. "
            "Failure at 20% suggests metallicity interpolation or endpoint quadrature bug."
        )

    def test_tengri_vs_bagpipes_vband_within_factor2(self, tengri, ref, ref_wave):
        """V-band agreement within factor 2 vs bagpipes (BC03 vs MILES SSPs)."""
        key = "bagpipes_stellar_starforming"
        if key not in ref:
            pytest.skip(f"Reference key {key!r} not in npz (bagpipes not installed?)")

        l_tengri = _band_avg(tengri["wave"], tengri["sed"], 5500.0)
        l_bagpipes = _band_avg(ref_wave, ref[key], 5500.0)

        ratio = l_tengri / l_bagpipes
        assert 0.5 <= ratio <= 2.0, (
            f"V-band L_nu/Msun ratio tengri/bagpipes = {ratio:.3f} (expect 0.5–2.0). "
            f"tengri={l_tengri:.3e}, bagpipes={l_bagpipes:.3e} erg/s/Hz/Msun. "
            "SSP library difference (MILES vs BC03) accounts for ~50%; "
            "larger deviations indicate a normalisation bug."
        )

    def test_tengri_vs_cigale_vband_within_factor2(self, tengri, ref, ref_wave):
        """V-band agreement within factor 2 vs CIGALE (BC03 vs MILES SSPs)."""
        key = "cigale_stellar_starforming"
        if key not in ref:
            pytest.skip(f"Reference key {key!r} not in npz (CIGALE not installed?)")

        l_tengri = _band_avg(tengri["wave"], tengri["sed"], 5500.0)
        l_cigale = _band_avg(ref_wave, ref[key], 5500.0)

        ratio = l_tengri / l_cigale
        assert 0.5 <= ratio <= 2.0, (
            f"V-band L_nu/Msun ratio tengri/CIGALE = {ratio:.3f} (expect 0.5–2.0). "
            f"tengri={l_tengri:.3e}, cigale={l_cigale:.3e} erg/s/Hz/Msun."
        )

    def test_tengri_sed_is_finite_and_positive(self, tengri):
        """SED must be finite and positive throughout the optical range."""
        wave = tengri["wave"]
        sed = tengri["sed"]
        optical = (wave > 1000.0) & (wave < 30000.0)
        assert np.all(np.isfinite(sed[optical])), "NaN or Inf in tengri SED optical range"
        assert np.all(sed[optical] >= 0.0), "Negative flux in tengri SED optical range"

    def test_m_formed_is_correct(self, tengri):
        """SFR=1 Msun/yr over 3 Gyr should give M_formed = 3e9 Msun."""
        assert abs(tengri["m_formed"] - 3.0e9) < 1e3, (
            f"Expected M_formed = 3e9 Msun, got {tengri['m_formed']:.3e}"
        )


