        try:
            from tengri.models.dust.attenuation import calzetti_attenuation
        except ImportError:
            pytest.skip("calzetti_attenuation not importable")

        wave_t, sed_clean, _ = _build_tengri_sed(ssp_data, start_gyr=0.0, end_gyr=1.0)
