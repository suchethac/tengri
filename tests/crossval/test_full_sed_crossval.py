class TestOldQuenched:
    """Tengri vs external codes: 10 Gyr galaxy, SF from 0–5 Gyr, then quenched."""

    @pytest.fixture(scope="class")
    def tengri(self, ssp_data):
        # tengri: start=5.0 (5 Gyr lookback), end=10.0 (10 Gyr lookback)
        # = SF from formation to 5 Gyr after formation, observed at 10 Gyr
        wave, sed_per_msun, m_formed = _build_tengri_sed(ssp_data, start_gyr=5.0, end_gyr=10.0)
        return {"wave": wave, "sed": sed_per_msun, "m_formed": m_formed}

    def test_tengri_vs_fsps_vband(self, tengri, ref, ref_wave):
        """V-band luminosity per Msun within 10% of FSPS (quenched, 5 Gyr SF, 10 Gyr obs).

        Same SSPs (MILES, Chabrier), identical SFH definition. Tight tolerance
        catches CSP time-weighting errors for old stellar populations.
        """
        key = "fsps_stellar_old_quenched"
        if key not in ref:
            pytest.skip(f"Reference key {key!r} not in npz")

        l_tengri = _band_avg(tengri["wave"], tengri["sed"], 5500.0)
        l_fsps = _band_avg(ref_wave, ref[key], 5500.0)

        ratio = l_tengri / l_fsps
        assert 0.90 <= ratio <= 1.10, (
            f"V-band L_nu/Msun ratio tengri/FSPS = {ratio:.3f} (old_quenched). "
            f"tengri={l_tengri:.3e}, fsps={l_fsps:.3e} erg/s/Hz/Msun. "
            "Same SSPs: 10% threshold. Failure → SFH truncation bug or CSP endpoint error."
        )

    def test_quenched_redder_than_starforming_in_tengri(self, ssp_data):
        """Old quenched galaxy should be redder (higher V/UV ratio) than star-forming.

        A quenched galaxy has no young stars, so its UV flux (relative to V) should
        be much lower than a star-forming galaxy. Failure here indicates a bug in
        the SFH truncation logic or CSP time-weighting.
        """
        _, sf_sed, _ = _build_tengri_sed(ssp_data, start_gyr=0.0, end_gyr=3.0)
        _, qu_sed, _ = _build_tengri_sed(ssp_data, start_gyr=5.0, end_gyr=10.0)
        wave = np.asarray(ssp_data.ssp_wave)

        # UV-to-V flux ratio (smaller = redder)
        sf_uv = _band_avg(wave, sf_sed, 2800.0, half_width=200.0)
        sf_v = _band_avg(wave, sf_sed, 5500.0)
        qu_uv = _band_avg(wave, qu_sed, 2800.0, half_width=200.0)
        qu_v = _band_avg(wave, qu_sed, 5500.0)

        sf_ratio = sf_uv / sf_v
        qu_ratio = qu_uv / qu_v

        assert qu_ratio < sf_ratio, (
            f"Quenched galaxy is NOT redder than star-forming: "
            f"quenched UV/V = {qu_ratio:.3f}, SF UV/V = {sf_ratio:.3f}. "
            "This indicates a SFH truncation bug — the quenched model "
            "may still have young stars contributing UV flux."
        )

    def test_m_formed_is_correct(self, tengri):
        """SFR=1 Msun/yr over 5 Gyr should give M_formed = 5e9 Msun."""
        assert abs(tengri["m_formed"] - 5.0e9) < 1e3, (
            f"Expected M_formed = 5e9 Msun, got {tengri['m_formed']:.3e}"
        )


